/**
 * Normalize player data to match what different storage adapters return.
 * - Supabase: Only stores id, name, defaultPosition and normalizes computed values to 0
 * - Dexie: Stores full object including computed values
 * Use flexible matchers to accommodate both approaches.
 */
function normalizePlayerForStorage(player: any): any {
  const normalized: any = {
    id: player.id,
    name: player.name,
    defaultPosition: player.defaultPosition,
    positions: [player.defaultPosition], // Reconstructed from defaultPosition
    overallRank: expect.any(Number), // May be 0 (Supabase) or computed value (Dexie)
    positionRank: expect.any(Number), // May be 0 (Supabase) or computed value (Dexie)
  };

  // suggestedCost may be present (Dexie) or absent (Supabase)
  if (player.suggestedCost !== undefined) {
    normalized.suggestedCost = expect.any(Number);
  }

  return normalized;
}

/**
 * Normalize live draft pick by removing computed player values
 */
function normalizeLiveDraftPickForStorage(pick: LiveDraftPick): LiveDraftPick {
  return {
    ...pick,
    player: normalizePlayerForStorage(pick.player)
  };
}

/**
 * Normalize live draft data to accommodate differences between storage adapters.
 * - Supabase: Reconstructs minimal stateSnapshot with computed values  
 * - Dexie: Stores complete stateSnapshot as provided
 * Use flexible matchers to accommodate both approaches.
 */
function normalizeLiveDraftForStorage(draft: LiveDraftState): LiveDraftState {
  const normalizedPicks = draft.picks.map(normalizeLiveDraftPickForStorage);
  
  return {
    ...draft,
    // Timestamps are stored but generated by database - normalize for testing
    created: expect.any(Number),
    modified: expect.any(Number),
    picks: normalizedPicks,
    // stateSnapshot varies by adapter - use flexible matchers
    stateSnapshot: {
      pickNumber: expect.any(Number),
      totalBudgetSpentPct: expect.any(Number),
      budgetSpentByPositionPct: expect.any(Object), // May be empty (Supabase) or populated (Dexie)
      playersPickedByPosition: expect.any(Object), // May be empty (Supabase) or populated (Dexie)
      budgetDistribution: {
        averageRemainingPct: expect.any(Number),
        medianRemainingPct: expect.any(Number), // May be 0 (Supabase) or computed (Dexie)
        minRemainingPct: expect.any(Number),
        maxRemainingPct: expect.any(Number),
        teamsWithLowBudgetPct: expect.any(Number) // May be 0 (Supabase) or computed (Dexie)
      },
      positionScarcityMetrics: expect.any(Object) // May be empty (Supabase) or populated (Dexie)
    }
  };
}

