  // Normalize only the expected data to match what storage should persist
  expect(loadedDraft1).toEqual(normalizeLiveDraftForStorage(draft1));
  expect(loadedDraft2).toEqual(normalizeLiveDraftForStorage(draft2));
  
  // Test pick ordering is maintained
  const testDraft = createTestLiveDraftState({ leagueId: testLeagueId, picks: [] });
  await adapter.saveLiveDraft(testLeagueId, testDraft);
  
  // Add picks in specific order
  const picks = [
    createTestLiveDraftPick({ pickNumber: 1 }),
    createTestLiveDraftPick({ pickNumber: 3 }),
    createTestLiveDraftPick({ pickNumber: 2 })
  ];
  
  for (const pick of picks) {
    await adapter.addLiveDraftPick(testLeagueId, testDraft.draftId, pick);
  }
  
  const draftWithPicks = await adapter.loadLiveDraft(testLeagueId, testDraft.draftId);
  expect(draftWithPicks!.picks).toHaveLength(3);
  
  // Verify picks can be retrieved in any order
  expect(draftWithPicks!.picks.find(p => p.pickNumber === 1)).toBeDefined();
  expect(draftWithPicks!.picks.find(p => p.pickNumber === 2)).toBeDefined();
  expect(draftWithPicks!.picks.find(p => p.pickNumber === 3)).toBeDefined();
