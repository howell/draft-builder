/**
 * Test a storage adapter's live draft CRUD operations
 */
export async function testLiveDraftStorageCRUD(adapter: StorageAdapter) {
  const testLeagueId = TEST_LEAGUE_ID;
  const testLeague = createTestLeague({ id: testLeagueId });
  
  // Set up league first (required for live drafts)
  await adapter.saveLeague(testLeagueId, testLeague);
  
  // Create test live draft state
  const liveDraftState = createTestLiveDraftState({ leagueId: testLeagueId });
  
  // Test saving and loading a live draft
  await adapter.saveLiveDraft(testLeagueId, liveDraftState);
  const loadedDraft = await adapter.loadLiveDraft(testLeagueId, liveDraftState.draftId);
  
  // Normalize only the expected data to match what storage should persist
  const expectedNormalized = normalizeLiveDraftForStorage(liveDraftState);
  expect(loadedDraft).toEqual(expectedNormalized);
  
  // Test loading all live drafts for a league
  const allDrafts = await adapter.loadLiveDrafts(testLeagueId);
  expect(allDrafts).toHaveLength(1);
  expect(allDrafts[0]).toEqual(expectedNormalized);
  
  // Test adding a pick
  const newPick = createTestLiveDraftPick({ 
    pickNumber: liveDraftState.picks.length + 1,
    teamId: liveDraftState.teams[0].id,
    teamName: liveDraftState.teams[0].name
  });
  
  await adapter.addLiveDraftPick(testLeagueId, liveDraftState.draftId, newPick);
  
  const draftWithNewPick = await adapter.loadLiveDraft(testLeagueId, liveDraftState.draftId);
  expect(draftWithNewPick!.picks).toHaveLength(liveDraftState.picks.length + 1);
  
  // Normalize only the expected pick to match what storage should persist
  const expectedPick = normalizeLiveDraftPickForStorage(newPick);
  const actualPick = draftWithNewPick!.picks[draftWithNewPick!.picks.length - 1];
  expect(actualPick).toEqual(expectedPick);
  
  // Test updating a pick
  const updatedPick = { ...newPick, price: newPick.price + 10 };
  await adapter.updateLiveDraftPick(testLeagueId, liveDraftState.draftId, newPick.pickNumber, updatedPick);
  
  const draftWithUpdatedPick = await adapter.loadLiveDraft(testLeagueId, liveDraftState.draftId);
  const foundUpdatedPick = draftWithUpdatedPick!.picks.find(p => p.pickNumber === newPick.pickNumber);
  
  // Normalize only the expected pick to match what storage should persist
  const expectedUpdatedPick = normalizeLiveDraftPickForStorage(updatedPick);
  expect(foundUpdatedPick).toEqual(expectedUpdatedPick);
  
  // Test deleting a pick
  await adapter.deleteLiveDraftPick(testLeagueId, liveDraftState.draftId, newPick.pickNumber);
  
  const draftWithDeletedPick = await adapter.loadLiveDraft(testLeagueId, liveDraftState.draftId);
  expect(draftWithDeletedPick!.picks).toHaveLength(liveDraftState.picks.length);
  expect(draftWithDeletedPick!.picks.find(p => p.pickNumber === newPick.pickNumber)).toBeUndefined();
  
  // Test deleting the entire draft
  await adapter.deleteLiveDraft(testLeagueId, liveDraftState.draftId);
  const deletedDraft = await adapter.loadLiveDraft(testLeagueId, liveDraftState.draftId);
  expect(deletedDraft).toBeUndefined();
  
  const allDraftsAfterDelete = await adapter.loadLiveDrafts(testLeagueId);
  expect(allDraftsAfterDelete).toHaveLength(0);
}

